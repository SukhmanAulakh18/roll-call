// make slo: slo/*.yaml (OpenSLO v1, Prometheus ratio SLIs) -> deploy/observability/prometheus/rules/slo.rules.yml
// Recording rules per window, burn-rate recordings, 30 d error-budget remaining, and multi-window burn-rate alerts.
// Zero deps, so the YAML reader below handles only the subset slo/*.yaml uses (block maps, "- " lists, plain/single/double-quoted scalars).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

type Y = string | Y[] | { [k: string]: Y };
export function parseYaml(src: string): Y {
  const lines = src.split('\n').filter(l => l.trim() && !l.trim().startsWith('#')).map(l => ({ ind: l.length - l.trimStart().length, t: l.trim() }));
  const scalar = (v: string): string => v[0] === "'" ? v.slice(1, -1).replace(/''/g, "'") : v[0] === '"' ? JSON.parse(v) : v;
  let i = 0;
  function block(ind: number): Y {
    if (lines[i].t.startsWith('- ')) {
      const out: Y[] = [];
      while (i < lines.length && lines[i].ind === ind && lines[i].t.startsWith('- ')) { lines[i] = { ind: ind + 2, t: lines[i].t.slice(2) }; out.push(block(ind + 2)); }
      return out;
    }
    const out: { [k: string]: Y } = {};
    while (i < lines.length && lines[i].ind === ind && !lines[i].t.startsWith('- ')) {
      const m = /^([\w.-]+):\s*(.*)$/.exec(lines[i].t); if (!m) throw new Error(`bad yaml line: ${lines[i].t}`);
      i++;
      out[m[1]] = m[2] ? scalar(m[2]) : i < lines.length && lines[i].ind > ind || (i < lines.length && lines[i].ind === ind && lines[i].t.startsWith('- ')) ? block(lines[i].ind) : '';
    }
    return out;
  }
  return block(lines[0].ind);
}

const WINDOWS = ['5m', '30m', '1h', '6h', '3d', '30d'];
const ALERTS = [ // burn-rate multiple, long window, short window (both must exceed)
  { severity: 'page', burn: 14.4, long: '1h', short: '5m', note: '2% of the 30 d budget in 1 h' },
  { severity: 'ticket', burn: 6, long: '6h', short: '30m', note: '5% of the 30 d budget in 6 h' },
  { severity: 'review', burn: 1, long: '3d', short: '6h', note: 'budget spent exactly at the rate that exhausts it in 30 d' },
];

export function generate(files: Record<string, string>): string {
  const out = ['# GENERATED by scripts/slo-gen.ts from slo/*.yaml. Do not edit; run `make slo`.', 'groups:'];
  for (const [file, src] of Object.entries(files)) {
    const d = parseYaml(src) as any, name: string = d.metadata.name, svc: string = d.spec.service, o = d.spec.objectives[0];
    const target = Number(o.target), q = (k: 'good' | 'total', w: string) => (o.ratioMetrics[k].metricSource.spec.query as string).replaceAll('$window', w);
    if (!(target > 0 && target < 1)) throw new Error(`${file}: target must be in (0,1)`);
    const lab = `{slo="${name}",service="${svc}"}`, budget = +(1 - target).toPrecision(10);
    out.push(`  - name: slo-${name}`, '    interval: 30s', '    rules:');
    for (const w of WINDOWS) out.push(`      - record: slo:sli_error:ratio_rate${w}`, `        expr: 1 - ((${q('good', w)}) / (${q('total', w)}))`, `        labels: { slo: ${name}, service: ${svc} }`);
    for (const w of WINDOWS.slice(0, 5)) out.push(`      - record: slo:burn_rate:${w}`, `        expr: slo:sli_error:ratio_rate${w}${lab} / ${budget}`, `        labels: { slo: ${name}, service: ${svc} }`);
    out.push('      - record: slo:objective:ratio', `        expr: vector(${target})`, `        labels: { slo: ${name}, service: ${svc} }`);
    // Budget remaining over the rolling 30 d window. 1 = untouched, 0 = exhausted, below 0 = overspent. This is the signal the promotion gate reads (docs/slo.md).
    out.push('      - record: slo:error_budget_remaining:ratio', `        expr: 1 - (slo:sli_error:ratio_rate30d${lab} / ${budget})`, `        labels: { slo: ${name}, service: ${svc} }`);
    for (const a of ALERTS) out.push(
      '      - alert: SLOBurnRate', `        expr: slo:burn_rate:${a.long}${lab} > ${a.burn} and slo:burn_rate:${a.short}${lab} > ${a.burn}`,
      `        labels: { severity: ${a.severity}, slo: ${name}, service: ${svc}, window: ${a.long} }`,
      '        annotations:', `          summary: '${o.displayName}: burning error budget at over ${a.burn}x (${a.note}).'`, '          runbook: docs/slo.md');
  }
  return out.join('\n') + '\n';
}

if (process.argv[1]?.endsWith('slo-gen.ts')) {
  const files = Object.fromEntries(readdirSync('slo').filter(f => f.endsWith('.yaml')).sort().map(f => [f, readFileSync(`slo/${f}`, 'utf8')]));
  writeFileSync('deploy/observability/prometheus/rules/slo.rules.yml', generate(files));
  console.log(`wrote slo.rules.yml from ${Object.keys(files).length} SLOs`);
}
